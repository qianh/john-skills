import { afterEach, describe, expect, test } from "bun:test"
import { spawnSync } from "node:child_process"
import { chmodSync, existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, symlinkSync, writeFileSync } from "node:fs"
import { tmpdir } from "node:os"
import path from "node:path"
import { SnapshotManager, checkSafety } from "./snapshot.ts"
import { safeEnv } from "./safety.ts"

const roots: string[] = []
afterEach(() => { for (const root of roots.splice(0)) rmSync(root, { recursive: true, force: true }) })

function fixture() {
  const root = mkdtempSync(path.join(tmpdir(), "orch-snapshot-test-"))
  roots.push(root)
  const cwd = path.join(root, "repo")
  mkdirSync(cwd)
  const git = (...args: string[]) => {
    const proc = spawnSync("git", args, { cwd, encoding: "utf8", env: safeEnv("verify", [], root) })
    if (proc.status !== 0) throw new Error(`Fixture git ${args[0]} failed`)
    return proc.stdout
  }
  const write = (file: string, content: string) => {
    mkdirSync(path.dirname(path.join(cwd, file)), { recursive: true })
    writeFileSync(path.join(cwd, file), content)
  }
  const commit = () => { git("add", "-A"); git("-c", "user.name=Snapshot Test", "-c", "user.email=snapshot@example.invalid", "-c", "commit.gpgsign=false", "commit", "-qm", "fixture") }
  git("init", "-q")
  const manager = () => new SnapshotManager(cwd, path.join(root, "run"))
  const indexBytes = () => readFileSync(path.resolve(cwd, git("rev-parse", "--git-path", "index").trim()))
  return { root, cwd, git, write, commit, manager, indexBytes }
}

describe("safe workspace snapshots", () => {
  test("captures staged, unstaged, untracked, staged-deleted and mode changes without touching the index", () => {
    const f = fixture()
    for (const name of ["staged.txt", "unstaged.txt", "deleted.txt", "mode.sh"]) f.write(name, "original\n")
    f.commit()
    f.write("staged.txt", "staged\n")
    f.git("add", "staged.txt")
    f.write("unstaged.txt", "unstaged\n")
    f.git("rm", "-q", "deleted.txt")
    f.write("new.txt", "preexisting new\n")
    chmodSync(path.join(f.cwd, "mode.sh"), 0o755)
    const before = f.indexBytes()
    const manager = f.manager()
    const baseline = manager.captureBaseline()
    expect(baseline.preexisting.sort()).toEqual(["deleted.txt", "mode.sh", "new.txt", "staged.txt", "unstaged.txt"])
    expect(f.indexBytes()).toEqual(before)
    f.write("staged.txt", "worker update\n")
    f.write("new.txt", "worker new update\n")
    const current = manager.captureSnapshot()
    expect(manager.changedPaths(baseline.tree, current.tree)).toEqual(["new.txt", "staged.txt"])
    expect(manager.diffTrees(baseline.tree, current.tree)).toContain("worker new update")
    expect(checkSafety(baseline, current)).toEqual([])
    expect(f.indexBytes()).toEqual(before)
    expect(f.git("ls-tree", baseline.tree, "mode.sh")).toStartWith("100755")
    expect(f.git("ls-tree", baseline.tree, "deleted.txt")).toBe("")
  })

  test("excludes tracked, untracked and ignored sensitive paths before git add and only records stat", () => {
    const f = fixture()
    f.write(".env", "synthetic tracked value\n")
    f.write("visible.txt", "baseline\n")
    f.write(".gitignore", ".env.local\nignored-dir/\n")
    f.commit()
    f.write(".env.local", "synthetic ignored value\n")
    f.write("secrets/nested.txt", "synthetic untracked value\n")
    f.write("ignored-dir/hidden.key", "ignored folded directory\n")
    chmodSync(path.join(f.cwd, ".env"), 0)
    const before = f.indexBytes()
    const manager = f.manager()
    const baseline = manager.captureBaseline()
    expect(Object.keys(baseline.sensitive).sort()).toEqual([".env", ".env.local", "secrets/nested.txt"])
    for (const tree of [baseline.tree, baseline.safeHead]) {
      const paths = f.git("ls-tree", "-r", "--name-only", tree)
      expect(paths).not.toContain(".env")
      expect(paths).not.toContain("secret")
      expect(paths).not.toContain("hidden.key")
    }
    expect(manager.diffTrees(baseline.safeHead, baseline.tree)).not.toContain(".env")
    expect(f.indexBytes()).toEqual(before)
    chmodSync(path.join(f.cwd, ".env"), 0o600)
    f.write(".env", "synthetic changed value with different size\n")
    f.write("new.key", "synthetic newly-created value\n")
    f.write("visible.txt", "worker\n")
    const current = manager.captureSnapshot()
    expect(manager.changedPaths(baseline.tree, current.tree)).toEqual(["visible.txt"])
    expect(checkSafety(baseline, current)).toEqual(["sensitive-path-changed:.env", "sensitive-path-changed:new.key"])
  })

  test("supports unborn repositories and does not create the real index", () => {
    const f = fixture()
    f.write("new.txt", "new\n")
    const manager = f.manager()
    const baseline = manager.captureBaseline()
    expect(baseline.head).toBeNull()
    expect(baseline.preexisting).toEqual(["new.txt"])
    expect(existsSync(path.join(f.cwd, ".git/index"))).toBe(false)
    expect(f.git("ls-tree", "-r", "--name-only", baseline.safeHead)).toBe("")
  })

  test("clears assume-unchanged only in its temporary index", () => {
    const f = fixture()
    f.write("tracked.txt", "before\n")
    f.commit()
    f.git("update-index", "--assume-unchanged", "tracked.txt")
    f.write("tracked.txt", "hidden edit\n")
    const before = f.indexBytes()
    const baseline = f.manager().captureBaseline()
    expect(baseline.preexisting).toEqual(["tracked.txt"])
    expect(f.git("show", `${baseline.tree}:tracked.txt`)).toBe("hidden edit\n")
    expect(f.indexBytes()).toEqual(before)
    expect(f.git("ls-files", "-v")).toStartWith("h ")
  })

  test("rejects skip-worktree, sparse checkout, conflicts and non-git directories", () => {
    const f = fixture()
    f.write("tracked.txt", "before\n")
    f.commit()
    f.git("update-index", "--skip-worktree", "tracked.txt")
    expect(() => f.manager()).toThrow("skip-worktree")
    f.git("update-index", "--no-skip-worktree", "tracked.txt")
    f.git("config", "core.sparseCheckout", "true")
    expect(() => f.manager()).toThrow("Sparse")
    f.git("config", "core.sparseCheckout", "false")
    const oid = f.git("rev-parse", "HEAD:tracked.txt").trim()
    const env = { ...safeEnv("verify", [], f.root), GIT_INDEX_FILE: path.join(f.cwd, ".git/index") }
    const conflict = spawnSync("git", ["update-index", "--index-info"], { cwd: f.cwd, env, input: `0 ${"0".repeat(40)}\ttracked.txt\n100644 ${oid} 1\ttracked.txt\n100644 ${oid} 2\ttracked.txt\n100644 ${oid} 3\ttracked.txt\n` })
    expect(conflict.status).toBe(0)
    expect(() => f.manager()).toThrow("conflicts")
    expect(() => new SnapshotManager(f.root, path.join(f.root, "not-a-run"))).toThrow()
  })

  test("uses literal NUL-delimited paths and records symlink text, not its target", () => {
    const f = fixture()
    f.write(":(glob)*.txt", "literal\n")
    f.write("with\nnewline.txt", "newline\n")
    writeFileSync(path.join(f.root, "outside"), "must not be followed\n")
    symlinkSync(path.join(f.root, "outside"), path.join(f.cwd, "link"))
    const snapshot = f.manager().captureBaseline()
    expect(snapshot.preexisting).toEqual([":(glob)*.txt", "link", "with\nnewline.txt"])
    expect(f.git("ls-tree", snapshot.tree, "link")).toStartWith("120000")
    expect(f.git("show", `${snapshot.tree}:link`)).toBe(path.join(f.root, "outside"))
    const selected = f.manager().diffTrees(snapshot.safeHead, snapshot.tree, [":(glob)*.txt"])
    expect(selected).toContain("literal")
    expect(selected).not.toContain("newline")
    expect(f.manager().diffTrees(snapshot.safeHead, snapshot.tree, [])).toBe("")
  })

  test("does not recurse a directory replacing a tracked file", () => {
    const f = fixture()
    f.write("replaced", "old\n")
    f.commit()
    rmSync(path.join(f.cwd, "replaced"))
    f.write("replaced/safe.txt", "safe\n")
    f.write("replaced/.env", "do not snapshot\n")
    const snapshot = f.manager().captureBaseline()
    expect(f.git("ls-tree", "-r", "--name-only", snapshot.tree)).toBe("replaced/safe.txt\n")
  })

  test("does not follow a symlink replacing an ancestor of tracked paths", () => {
    const f = fixture()
    f.write("nested/a.txt", "before\n")
    f.write("nested/.env", "synthetic before\n")
    f.commit()
    const manager = f.manager()
    const baseline = manager.captureBaseline()
    rmSync(path.join(f.cwd, "nested"), { recursive: true })
    const external = path.join(f.root, "external")
    mkdirSync(external)
    writeFileSync(path.join(external, "a.txt"), "external content must stay outside\n")
    writeFileSync(path.join(external, ".env"), "synthetic external value\n")
    symlinkSync(external, path.join(f.cwd, "nested"))
    const before = f.indexBytes()
    const current = manager.captureSnapshot()
    expect(f.git("ls-tree", current.tree, "nested")).toStartWith("120000")
    expect(f.git("show", `${current.tree}:nested`)).toBe(external)
    expect(manager.diffTrees(baseline.tree, current.tree)).not.toContain("external content must stay outside")
    expect(f.indexBytes()).toEqual(before)
  })

  test("detects actual HEAD/index changes while ordinary worktree edits are safe", () => {
    const f = fixture()
    f.write("a.txt", "before\n")
    f.commit()
    const manager = f.manager()
    const baseline = manager.captureBaseline()
    f.write("a.txt", "after\n")
    expect(checkSafety(baseline, manager.captureSnapshot())).toEqual([])
    f.git("add", "a.txt")
    expect(checkSafety(baseline, manager.captureSnapshot())).toEqual(["index-changed"])
    f.commit()
    expect(checkSafety(baseline, manager.captureSnapshot())).toEqual(["head-changed", "index-changed"])
  })

  test("resolves a linked worktree's private git directory and preserves its index", () => {
    const f = fixture()
    f.write("a.txt", "main\n")
    f.commit()
    const worktree = path.join(f.root, "worktree")
    f.git("worktree", "add", "-qb", "linked", worktree)
    const manager = new SnapshotManager(worktree, path.join(f.root, "run-linked"))
    expect(manager.gitDir).toContain(".git/worktrees/")
    const index = path.join(manager.gitDir, "index")
    const before = readFileSync(index)
    writeFileSync(path.join(worktree, "a.txt"), "linked update\n")
    expect(manager.captureBaseline().preexisting).toEqual(["a.txt"])
    expect(readFileSync(index)).toEqual(before)
    expect(readFileSync(path.join(f.cwd, "a.txt"), "utf8")).toBe("main\n")
  })

  test("safeHead accepts a base commit without exposing sensitive deletions", () => {
    const f = fixture()
    f.write("a.txt", "first\n")
    f.write(".env", "synthetic sensitive content\n")
    f.commit()
    const first = f.git("rev-parse", "HEAD").trim()
    f.write("a.txt", "second\n")
    f.commit()
    const manager = f.manager()
    const safe = manager.safeHead(first)
    expect(f.git("ls-tree", "-r", "--name-only", safe)).toBe("a.txt\n")
    expect(f.git("show", `${safe}:a.txt`)).toBe("first\n")
    expect(() => manager.safeHead("not-a-real-reference")).toThrow()
  })

  test("exports regular files only, scans copied text and never executes git filters", () => {
    const f = fixture()
    const value = "ghp_" + "A".repeat(36)
    f.write("a.txt", `before ${value} after\n`)
    f.write(".env", "synthetic excluded value\n")
    f.write(".gitattributes", "*.txt filter=probe\n")
    f.commit()
    symlinkSync("a.txt", path.join(f.cwd, "link"))
    f.git("config", "filter.probe.clean", `touch '${path.join(f.root, "filter-ran")}'`)
    f.git("config", "filter.probe.smudge", `touch '${path.join(f.root, "filter-ran")}'`)
    f.git("config", "filter.probe.required", "true")
    const manager = f.manager()
    const snapshot = manager.captureSnapshot()
    const target = path.join(f.root, "export")
    mkdirSync(target)
    const exported = manager.exportSafeTree(snapshot.tree, target)
    expect(exported.skipped).toEqual(["link"])
    expect(exported.flags).toEqual(["github-token:a.txt"])
    expect(readFileSync(path.join(target, "a.txt"), "utf8")).toBe("before [redacted:github-token] after\n")
    expect(readFileSync(path.join(f.cwd, "a.txt"), "utf8")).toContain(value)
    expect(existsSync(path.join(target, "link"))).toBe(false)
    expect(existsSync(path.join(target, ".env"))).toBe(false)
    expect(existsSync(path.join(f.root, "filter-ran"))).toBe(false)
    expect(() => manager.exportSafeTree(snapshot.tree, target)).toThrow("empty")
    const alias = path.join(f.root, "export-link")
    symlinkSync(target, alias)
    expect(() => manager.exportSafeTree(snapshot.tree, alias)).toThrow("non-symlink")
  })
})
